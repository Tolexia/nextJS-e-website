import Head from 'next/head'

import styles from '@/styles/Checkout.module.css'
import Cart from "@/components/cart"

import { useState } from 'react';
import { useRouter } from 'next/router';
import { useCart } from '@/components/cartContext';

function Checkout() {
    const [formData, setFormData] = useState({});
    const [submitting, setSubmitting] = useState(false);
    const [error, setError] = useState('');
    const router = useRouter();
    const { items, clearCart } = useCart();

    const handleInputChange = (e) => {
        setFormData({ ...formData, [e.target.name]: e.target.value });
      };
    
      const handleSubmit = async (e) => {
        e.preventDefault();
        setError('');

        if (!items.length) {
          setError('Ton panier est vide.');
          return;
        }

        setSubmitting(true);
        try {
          const response = await fetch('/api/orders/create', {
            method: 'POST',
            headers: {
              'Content-Type': 'application/json',
            },
            body: JSON.stringify({
              ...formData,
              items,
            }),
          });

          const payload = await response.json().catch(() => ({}));
          if (!response.ok) {
            throw new Error(payload.message || 'Erreur lors de la création de la commande');
          }

          clearCart();
          router.push('/order-confirmation');
        } catch (err) {
          console.error("Erreur lors de la création de la commande:", err);
          setError(err.message || 'Erreur lors de la création de la commande');
        } finally {
          setSubmitting(false);
        }
      };
  return (
    <>
      <Head>
        <title>Nextjs E-Website</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
        <main className={styles.mainSection}>
            <form onSubmit={handleSubmit} className={styles.form}>
                <h1>CHECKOUT</h1>
                {error ? <p role="alert" style={{ color: '#b00020' }}>{error}</p> : null}
                {/* Honeypot anti-bot: must stay empty */}
                <input
                  type="text"
                  name="website"
                  value={formData.website || ''}
                  onChange={handleInputChange}
                  autoComplete="off"
                  tabIndex={-1}
                  aria-hidden="true"
                  style={{ position: 'absolute', left: '-9999px', height: 0, width: 0, opacity: 0 }}
                />
                <div>
                <h3>BILLING DETAILS</h3>
                <div className={styles.formdiv}>
                <div>
                    <label htmlFor="name">Name</label>
                    <input type="text" name="name" id="name" onChange={handleInputChange} required />
                </div>
                <div>
                    <label htmlFor="email">Email Address</label>
                    <input type="email" name="email" id="email" onChange={handleInputChange} required />
                </div>
                <div>
                    <label htmlFor="phone">Phone Number</label>
                    <input type="tel" name="phone" id="phone" onChange={handleInputChange} required />
                </div>
                </div>
            </div>
            <div>
                <h3>SHIPPING INFO</h3>
                <div className={styles.formdiv}>
                <div>
                    <label htmlFor="address">Address</label>
                    <input type="text" name="address" id="address" onChange={handleInputChange} required />
                </div>
                <div>
                    <label htmlFor="zipcode">ZIP Code</label>
                    <input type="text" name="zipcode" id="zipcode" onChange={handleInputChange} required />
                </div>
                <div>
                    <label htmlFor="city">City</label>
                    <input type="text" name="city" id="city" onChange={handleInputChange} required />
                </div>
                <div>
                    <label htmlFor="country">Country</label>
                    <input type="text" name="country" id="country" onChange={handleInputChange} required />
                </div>
                </div>
            </div>
            <div>
                <h3>PAYMENT DETAILS</h3>
                <div className={styles.formdiv}>
                <div>
                    <label htmlFor="paymentMethod">Payment Method</label>
                    <select name="paymentMethod" id="paymentMethod" onChange={handleInputChange} required>
                    <option value="">Select</option>
                    <option value="e-Money">e-Money</option>
                    <option value="Cash on Delivery">Cash on Delivery</option>
                    </select>
                </div>
                <div>
                    <label htmlFor="emoneynumber">e-Money Number</label>
                    <input type="text" name="emoneynumber" id="emoneynumber" onChange={handleInputChange} placeholder='24304530' />
                </div>
                <div>
                    <label htmlFor="emoneypin">e-Money PIN</label>
                    <input type="password" name="emoneypin" id="emoneypin" onChange={handleInputChange} placeholder='6891' autoComplete="off" />
                </div>
                </div>
            </div>
            <button type="submit" className={styles.submitButton} disabled={submitting}>
              {submitting ? 'PROCESSING…' : 'CONTINUE & PAY'}
            </button>
            </form>
            <Cart/>
        </main>
    </>
  )
}

export default Checkout;
