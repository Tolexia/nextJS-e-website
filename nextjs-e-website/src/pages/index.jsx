import Head from 'next/head'
import Content from '@/components/content'
import { limitToFirst, orderByChild, ref, query, get, getDatabase } from 'firebase/database';
import firebase_app from "@/components/config"

function Home(pageProps) {
  // console.log(pageProps)
  const items = pageProps.items
  return (
    <>
      <Head>
        <title>Nextjs E-Website</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <Content items = {items} />
    </>
  )
}
Home.getInitialProps = async () => {
  try {
    const db = getDatabase(firebase_app);
    const snapshot = await get(query(ref(db, 'shoes'), orderByChild('name'), limitToFirst(5)));
    const value = snapshot.val();
    return { items: value ? Object.entries(value) : [] };
  } catch (error) {
    console.error(error);
    return { items: [] };
  }
}
export default Home;
